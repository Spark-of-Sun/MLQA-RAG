"""Generate the lifecycle transition table and triggers from contracts/state-machines.yaml (blueprint 6.1, R-10.2).

State machines are data: the YAML is the single source. This script renders it as one forward-only Alembic revision
(db/migrations/<revision>.sql plus its wrapper in lmqa_db/migrations/versions):

  state_transitions        every declared (machine, action, from, to) with its actors, guards and effects
  transition_<column>      one trigger per bound column (`bind:` in the YAML). It refuses an undeclared pair with
                           SQLSTATE 23514, whatever code path tries it. For a machine with `actor_check` it also
                           resolves the caller from the transaction context and refuses an actor the pair does not
                           list with SQLSTATE 42501 (insufficient_privilege)
  <table>_not_self         for a machine with `subject`: the subject (the member) can neither change the locked
                           columns of their own row nor delete it, except in the `may_delete` states

Actor resolution reads only the transaction-local context written by `lmqa_db.scoped()`: `app.user_id` (a person,
resolved to their relation with the row) or `app.actor` (a service acting without a user: `system`). With neither,
the caller is refused, except `lmqa_owner` (it owns the tables and could disable the triggers anyway; it never logs
in at runtime), which is still held to the declared pairs. Guards are evaluated by the services through
`lmqa_models.Machine.check`; the table stores their names.

An applied revision is never edited. When the YAML changes, write a new revision:

    python tools/state_machine_gen.py --check               # exit 1 if the newest generated revision is stale
    python tools/state_machine_gen.py --revision 0011_name  # new revision after the current head
    python tools/state_machine_gen.py --rewrite             # rewrite the newest generated revision (unreleased only)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

from lmqa_models.envfile import ROOT

SOURCE = ROOT / "contracts" / "state-machines.yaml"
MIGRATIONS = ROOT / "db" / "migrations"
VERSIONS = ROOT / "libs" / "lmqa_db" / "src" / "lmqa_db" / "migrations" / "versions"
HEADER = "-- GENERATED by tools/state_machine_gen.py from contracts/state-machines.yaml. Do not edit by hand."
OWNER = "lmqa_owner"

# How the caller relates to a row, per table of an `actor_check` machine. Each body sets v_actor from v_user (the
# person in app.user_id) and the row `old`; the no-user cases are handled before it runs.
RESOLVERS: dict[str, str] = {
    "memberships": """\
    elsif v_user = old.user_id then
        v_actor := 'member';
    elsif exists (select 1 from memberships m
                  where m.user_id = v_user and m.status = 'active'
                    and ((old.role = 'admin' and m.role = 'super_admin' and m.org_id = old.org_id)
                         or (old.role = 'tenant' and m.role = 'admin' and m.workspace_id = old.workspace_id))) then
        v_actor := 'approver';
    else
        v_actor := 'other';""",
    "workspaces": """\
    elsif exists (select 1 from memberships m where m.user_id = v_user and m.status = 'active'
                  and m.role = 'super_admin' and m.org_id = old.org_id) then
        v_actor := 'super_admin';
    elsif exists (select 1 from memberships m where m.user_id = v_user and m.status = 'active'
                  and m.role = 'admin' and m.workspace_id = old.id) then
        v_actor := 'admin';
    else
        v_actor := 'other';""",
}


def _q(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def _array(values: list[str]) -> str:
    return "array[" + ", ".join(_q(v) for v in values) + "]::text[]" if values else "'{}'::text[]"


def split_binding(binding: str) -> tuple[str, str]:
    table, _, column = binding.rpartition(".")
    return table, column


def bindings(doc: dict[str, Any]) -> dict[tuple[str, str], list[str]]:
    """(table, column) -> machines bound to it, in declaration order."""
    out: dict[tuple[str, str], list[str]] = {}
    for name, spec in doc["machines"].items():
        for binding in spec.get("bind", []):
            out.setdefault(split_binding(binding), []).append(name)
    return out


def problems(doc: dict[str, Any]) -> list[str]:  # noqa: C901 - one flat list of independent checks
    """Semantic checks the JSON schema cannot express."""
    out: list[str] = []
    actors, guards = set(doc["actors"]), set(doc["guards"])
    for name, spec in doc["machines"].items():
        states = set(spec["states"])
        for action, t in spec["transitions"].items():
            where = f"{name}.{action}"
            if not {t["from"], t["to"]} <= states:
                out.append(f"{where}: undeclared state")
            if t["from"] == t["to"]:
                out.append(f"{where}: from equals to")
            out += [f"{where}: unknown actor {a}" for a in set(t["actors"]) - actors]
            out += [f"{where}: unknown guard {g}" for g in set(t.get("guards", [])) - guards]
        if spec.get("actor_check"):
            for binding in spec.get("bind", []):
                if split_binding(binding)[0] not in RESOLVERS:
                    out.append(f"{name}: actor_check on {binding} has no resolver")
        subject = spec.get("subject")
        if subject and not set(subject["may_delete"]) <= states:
            out.append(f"{name}: subject.may_delete uses an undeclared state")
        if subject and len(spec.get("bind", [])) != 1:
            out.append(f"{name}: subject needs exactly one binding")
    for (table, column), machines in bindings(doc).items():
        checked = {bool(doc["machines"][m].get("actor_check")) for m in machines}
        if len(checked) > 1:
            out.append(f"{table}.{column}: machines disagree on actor_check")
    return out


def rows(doc: dict[str, Any]) -> list[tuple[str, str, str, str, list[str], list[str], list[str]]]:
    return sorted(
        (
            machine,
            action,
            t["from"],
            t["to"],
            sorted(t["actors"]),
            list(t.get("guards", [])),
            list(t.get("effects", [])),
        )
        for machine, spec in doc["machines"].items()
        for action, t in spec["transitions"].items()
    )


def _trigger(table: str, column: str, machines: list[str], actor_check: bool) -> list[str]:
    fn = f"app_transition_{table.replace('.', '_')}_{column}"
    machine_list = _array(machines)
    # Generated DDL from the reviewed contract: names are YAML identifiers, values are quoted by _q.
    pair = (
        f"select 1 from state_transitions t where t.machine = any ({machine_list})"  # noqa: S608
        f" and t.from_state = old.{column} and t.to_state = new.{column}"
    )
    out = [
        f"create or replace function {fn}() returns trigger",
        "    language plpgsql security definer set search_path = public, pg_temp",
        "as $$",
        "declare",
    ]
    if actor_check:
        out += [
            "    v_user  uuid := nullif(current_setting('app.user_id', true), '')::uuid;",
            "    v_tool  text := nullif(current_setting('app.actor', true), '');",
        ]
    out += [
        "    v_actor text;",
        "begin",
        f"    if old.{column} is not distinct from new.{column} then",
        "        return new;",
        "    end if;",
        f"    if not exists ({pair}) then",
        f"        raise exception 'illegal transition of {table}.{column}: % -> %', old.{column}, new.{column}",
        "            using errcode = '23514';",
        "    end if;",
    ]
    if actor_check:
        out += [
            "    if v_user is null then",
            "        v_actor := case when v_tool is not null then 'system'",
            f"                        when session_user = {_q(OWNER)} then 'owner' end;",
            RESOLVERS[table],
            "    end if;",
            f"    if v_actor is distinct from 'owner' and not exists ({pair} and v_actor = any (t.actors)) then",
            f"        raise exception 'actor % may not move {table}.{column}: % -> %',",
            f"            coalesce(v_actor, 'none'), old.{column}, new.{column} using errcode = '42501';",
            "    end if;",
        ]
    out += [
        "    return new;",
        "end",
        "$$;",
        f"revoke all on function {fn}() from public;",
        f"drop trigger if exists transition_{column} on {table};",
        f"create trigger transition_{column} before update of {column} on {table}",
        f"    for each row execute function {fn}();",
        "",
    ]
    return out


def _not_self(table: str, subject: dict[str, Any]) -> list[str]:
    fn = f"app_not_self_{table.replace('.', '_')}"
    name = f"{table.rpartition('.')[2]}_not_self"
    col = subject["column"]
    return [
        f"create or replace function {fn}() returns trigger",
        "    language plpgsql security definer set search_path = public, pg_temp",
        "as $$",
        "declare",
        "    v_user uuid := nullif(current_setting('app.user_id', true), '')::uuid;",
        "begin",
        f"    if v_user is null or v_user is distinct from old.{col} then",
        "        return coalesce(new, old);",
        "    end if;",
        "    if tg_op = 'DELETE' then",
        f"        if old.status = any ({_array(subject['may_delete'])}) then",
        "            return old;",
        "        end if;",
        f"        raise exception 'a member cannot delete their own {table} row in state %', old.status",
        "            using errcode = '42501';",
        "    end if;",
        f"    raise exception 'a member cannot change their own {table} row' using errcode = '42501';",
        "end",
        "$$;",
        f"revoke all on function {fn}() from public;",
        f"drop trigger if exists {name} on {table};",
        f"create trigger {name} before update of {', '.join(subject['locked'])} or delete on {table}",
        f"    for each row execute function {fn}();",
        "",
    ]


def render(doc: dict[str, Any]) -> str:
    found = problems(doc)
    if found:
        raise ValueError("contracts/state-machines.yaml: " + "; ".join(found))
    values = ",\n    ".join(
        f"({_q(m)}, {_q(a)}, {_q(f)}, {_q(t)}, {_array(ac)}, {_array(g)}, {_array(e)})"
        for m, a, f, t, ac, g, e in rows(doc)
    )
    out = [
        HEADER,
        "-- Lifecycle machines as data (blueprint 6.1, R-10.2, R-10.5): the transition table and one trigger per bound",
        "-- column. Forward-only, applied once by lmqa_owner through Alembic; a change to the YAML is a new revision.",
        "",
        "drop table if exists state_transitions;",
        "create table state_transitions (",
        "    machine    text not null,",
        "    action     text not null,",
        "    from_state text not null,",
        "    to_state   text not null,",
        "    actors     text[] not null check (cardinality(actors) > 0),",
        "    guards     text[] not null default '{}',",
        "    effects    text[] not null default '{}',",
        "    primary key (machine, action),",
        "    check (from_state <> to_state)",
        ");",
        "alter table state_transitions enable row level security;",
        "alter table state_transitions force row level security;",
        "create policy transitions_read on state_transitions for select using (true);",
        f"create policy transitions_owner on state_transitions for all to {OWNER} using (true) with check (true);",
        "insert into state_transitions (machine, action, from_state, to_state, actors, guards, effects) values",
        f"    {values};",
        "",
    ]
    for (table, column), machines in bindings(doc).items():
        actor_check = bool(doc["machines"][machines[0]].get("actor_check"))
        out += _trigger(table, column, machines, actor_check)
    for spec in doc["machines"].values():
        if spec.get("subject"):
            out += _not_self(split_binding(spec["bind"][0])[0], spec["subject"])
    out += [
        "-- The generic trigger function of db/policies/40_transitions.sql is replaced by the per-column ones above.",
        "drop function if exists app_check_transition();",
    ]
    return "\n".join(out) + "\n"


def load() -> dict[str, Any]:
    return yaml.safe_load(SOURCE.read_text(encoding="utf-8"))


def latest() -> Path | None:
    """The newest migration this script generated (the one the YAML must match)."""
    generated = [
        p
        for p in sorted(MIGRATIONS.glob("*.sql"))
        if p.read_text(encoding="utf-8").startswith(HEADER)
    ]
    return generated[-1] if generated else None


WRAPPER = '''"""Execute db/migrations/{rev}.sql (generated by tools/state_machine_gen.py from the state machines).

Revision ID: {rev}
Revises: {down}
"""

from __future__ import annotations

from alembic import op

from lmqa_db.migrations import sql_file

revision = "{rev}"
down_revision: str | None = "{down}"
branch_labels = None
depends_on = None


def upgrade() -> None:
    op.execute(sql_file(revision))


def downgrade() -> None:
    raise NotImplementedError("forward-only: restore from backup (blueprint 18)")
'''


def new_revision(name: str, body: str) -> Path:
    sql = MIGRATIONS / f"{name}.sql"
    if sql.exists() or (VERSIONS / f"{name}.py").exists():
        raise SystemExit(
            f"{name} exists; an applied revision is never edited (use --rewrite only before release)"
        )
    existing = sorted(p.stem for p in MIGRATIONS.glob("*.sql"))
    if existing and name <= existing[-1]:
        raise SystemExit(f"{name} must sort after the head {existing[-1]}")
    sql.write_text(body, encoding="utf-8")
    (VERSIONS / f"{name}.py").write_text(
        WRAPPER.format(rev=name, down=existing[-1]), encoding="utf-8"
    )
    return sql


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--check", action="store_true")
    group.add_argument("--revision", metavar="NNNN_name")
    group.add_argument("--rewrite", action="store_true")
    args = parser.parse_args()
    body = render(load())
    current = latest()
    if args.check:
        same = current is not None and current.read_text(encoding="utf-8") == body
        print(
            f"transitions: {current.name if current else 'no generated revision'} is up to date"
            if same
            else "transitions: OUT OF DATE (python tools/state_machine_gen.py --revision NNNN_name)"
        )
        return 0 if same else 1
    if args.revision:
        path = new_revision(args.revision, body)
    else:
        if current is None:
            raise SystemExit("no generated revision to rewrite; use --revision")
        current.write_text(body, encoding="utf-8")
        path = current
    print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
