"""Write docs/versions.md, the version ledger (blueprint 4.5, G0.1, G0.4).

The lockfiles and image digests are the authority; this file records what they resolve to so a reviewer can read it
and so tests can detect drift:

  Python packages     every third-party package in uv.lock
  Frontend packages   the direct dependencies resolved in frontend/pnpm-lock.yaml
  Container images    image and digest for each service in compose.yaml
  Servers             the versions the running servers report (`--servers` probes them; otherwise kept as is)
  Toolchain           Python, uv, ruff, pyright, Node.js and pnpm

`python tools/gen_versions.py` rewrites the ledger from the lockfiles; `--servers` also probes the running stack.
`--check` exits 1 when the ledger differs from what would be written (the G0.1 test uses the same functions).
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

import yaml

from lmqa_models.envfile import ROOT

LEDGER = ROOT / "docs" / "versions.md"
SECTIONS = ("Toolchain", "Servers", "Container images", "Frontend packages", "Python packages")
_ROW = re.compile(r"^\| `([^`]+)` \| `([^`]*)` \|")


def python_packages() -> dict[str, str]:
    lock = tomllib.loads((ROOT / "uv.lock").read_text(encoding="utf-8"))
    out: dict[str, str] = {}
    for pkg in lock.get("package", []):
        source = pkg.get("source", {})
        if "editable" in source or "virtual" in source or "workspace" in source:
            continue  # our own workspace packages
        out[pkg["name"]] = pkg["version"]
    return dict(sorted(out.items()))


def frontend_packages() -> dict[str, str]:
    lock = yaml.safe_load((ROOT / "frontend" / "pnpm-lock.yaml").read_text(encoding="utf-8"))
    importer = lock["importers"]["."]
    out: dict[str, str] = {}
    for group in ("dependencies", "devDependencies"):
        for name, spec in (importer.get(group) or {}).items():
            out[name] = str(spec["version"]).split("(", 1)[0]
    return dict(sorted(out.items()))


def container_images() -> dict[str, str]:
    compose = yaml.safe_load((ROOT / "compose.yaml").read_text(encoding="utf-8"))
    return {
        name: svc["image"] for name, svc in sorted(compose["services"].items()) if "image" in svc
    }


def _tool(cmd: list[str], pattern: str) -> str:
    exe = shutil.which(cmd[0])
    if not exe:
        return "missing"
    out = subprocess.run([exe, *cmd[1:]], capture_output=True, text=True, check=False)  # noqa: S603 - fixed version-probe commands
    match = re.search(pattern, out.stdout + out.stderr)
    return match.group(1) if match else "unknown"


def toolchain() -> dict[str, str]:
    venv_bin = ROOT / ".venv" / "bin"
    return {
        "python": ".".join(map(str, sys.version_info[:3])),
        "uv": _tool(["uv", "--version"], r"uv (\S+)"),
        "ruff": _tool([str(venv_bin / "ruff"), "--version"], r"ruff (\S+)"),
        "pyright": python_packages().get("pyright", "missing"),
        "node": _tool(["node", "--version"], r"v(\S+)"),
        "pnpm": _tool(["pnpm", "--version"], r"(\d+\.\d+\.\d+)"),
    }


def servers() -> dict[str, str]:
    """Versions reported by the running servers (requires `make up`)."""
    from lmqa_testing.infra import server_versions

    return server_versions()


def read_ledger(path: Path = LEDGER) -> dict[str, dict[str, str]]:
    sections: dict[str, dict[str, str]] = {}
    current: str | None = None
    if not path.is_file():
        return sections
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            current = line[3:].strip()
            sections[current] = {}
        elif current and (m := _ROW.match(line)):
            sections[current][m.group(1)] = m.group(2)
    return sections


def render(data: dict[str, dict[str, str]]) -> str:
    lines = [
        "# Version ledger",
        "",
        "Generated by `tools/gen_versions.py` (blueprint 4.5). The lockfiles (`uv.lock`, `frontend/pnpm-lock.yaml`)",
        "and the image digests in `compose.yaml` are the authority; G0.1 fails when this file and the lockfiles",
        "disagree, and G0.4 fails when a running server reports a different version than **Servers** below.",
        "",
        "Versions newer than the blueprint's October 2026 baseline (Qdrant 1.20 instead of 1.19, Valkey 9.2 instead",
        "of 9.1, PostgreSQL 18.7 instead of 18.6, pytest 9.2 instead of 9.1, ruff 0.17 instead of 0.16) follow the",
        "adoption policy: general availability, a patch release, and a full cumulative gate run.",
        "",
        "Cryptography: audit payloads are sealed with HPKE (RFC 9180) through `cryptography`'s",
        "`hazmat.primitives.hpke` (OpenSSL; suite DHKEM(X25519, HKDF-SHA256), HKDF-SHA256, AES-256-GCM), and field",
        "encryption uses its `AESGCM`. No primitive is implemented in this repository.",
        "",
    ]
    for section in SECTIONS:
        lines += [f"## {section}", "", "| Name | Version |", "| --- | --- |"]
        lines += [f"| `{k}` | `{v}` |" for k, v in data.get(section, {}).items()]
        lines.append("")
    return "\n".join(lines)


def collect(*, probe_servers: bool) -> dict[str, dict[str, str]]:
    current = read_ledger()
    return {
        "Toolchain": toolchain(),
        "Servers": servers() if probe_servers else current.get("Servers", {}),
        "Container images": container_images(),
        "Frontend packages": frontend_packages(),
        "Python packages": python_packages(),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--servers", action="store_true", help="also probe the running servers")
    parser.add_argument("--check", action="store_true", help="exit 1 if the ledger is out of date")
    args = parser.parse_args()
    body = render(collect(probe_servers=args.servers))
    if args.check:
        same = LEDGER.is_file() and LEDGER.read_text(encoding="utf-8") == body
        print(
            "versions ledger: up to date"
            if same
            else "versions ledger: OUT OF DATE (run make versions)"
        )
        return 0 if same else 1
    LEDGER.write_text(body, encoding="utf-8")
    print(f"wrote {LEDGER.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
