"""Pre-flight check for the onekami.site server (docs/deploy.md), run by `make deploy-up`.

Reads the settings file LMQA_ENV_FILE names (`.env.deployed` on the server) and the shell, and stops with the names of
the settings that are missing or wrong. Values are never printed.
"""

from __future__ import annotations

import sys

from lmqa_models.envfile import ENV_FILE, is_placeholder, merged_env

REQUIRED = {
    "AUTH0_DOMAIN": "Auth0 tenant domain",
    "AUTH0_AUDIENCE_MAIN": "identifier of the Auth0 API",
    "GEMINI_API_KEY": "answer model key (Google AI Studio)",
    "CLOUDFLARE_TUNNEL_TOKEN": "token of the Cloudflare Tunnel (Zero Trust -> Networks -> Tunnels)",
    "LMQA_DB_SUPERUSER_PASSWORD": "generated by `make deploy-setup`",
    "OPENBAO_TOKEN": "generated by `make deploy-setup`",
    "CODE_PEPPER_V1": "generated by `make deploy-setup`",
}


def main() -> int:
    if not ENV_FILE.is_file():
        print(f"{ENV_FILE.name} not found in the repo root (run tools/unpack-ignored.sh first)")
        return 1
    env = merged_env()
    problems = [f"{k}: {why}" for k, why in REQUIRED.items() if is_placeholder(env.get(k))]
    if env.get("EMBEDDING_PROVIDER", "gemini").strip().lower() != "local":
        problems.append("EMBEDDING_PROVIDER: must be `local` on the server")
    if not env.get("APP_BASE_URL", "").startswith("https://"):
        problems.append("APP_BASE_URL: must be https://onekami.site")
    if problems:
        print(f"{ENV_FILE.name} is not ready:")
        for p in problems:
            print(f"  - {p}")
        return 1
    print(f"{ENV_FILE.name}: required settings present")
    return 0


if __name__ == "__main__":
    sys.exit(main())
