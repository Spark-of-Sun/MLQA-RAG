"""Generate strong random LOCAL secrets into `.secrets.generated` (never touches `.env` or `.secrets`).

Only settings missing from every layer (or still placeholders) are generated. Values are never printed.
"""

from __future__ import annotations

import os
import secrets
import sys

from lmqa_models.envfile import GENERATED, USER_FILES, is_placeholder, merged_env, parse_env_file

GENERATORS = {
    "LMQA_DB_SUPERUSER_PASSWORD": lambda: secrets.token_urlsafe(24),
    "LMQA_DB_OWNER_PASSWORD": lambda: secrets.token_urlsafe(24),
    "LMQA_DB_APP_PASSWORD": lambda: secrets.token_urlsafe(24),
    "LMQA_DB_SYSTEM_PASSWORD": lambda: secrets.token_urlsafe(24),
    "CODE_PEPPER_V1": lambda: secrets.token_hex(32),
    "AUTH0_SESSION_SECRET": lambda: secrets.token_hex(32),
}


def main() -> int:
    effective = merged_env()
    existing = parse_env_file(GENERATED)
    added = [k for k in GENERATORS if is_placeholder(effective.get(k))]
    if added:
        existing.update({k: GENERATORS[k]() for k in added})
        body = (
            "# Generated by `make setup`: local-only secrets. Never commit.\n"
            "# The database passwords are baked into the Docker volume: keep this file while the volume exists,\n"
            "# or run `make db-reset` (deletes local data) to start over.\n"
        )
        body += "".join(f"{k}={v}\n" for k, v in sorted(existing.items()))
        GENERATED.write_text(body, encoding="utf-8")
        os.chmod(GENERATED, 0o600)
        print(f"generated local secrets: {', '.join(added)}")
    else:
        print("local secrets: already present")
    if not any(p.is_file() for p in USER_FILES):
        print("note: no .env found; put your Auth0 and Gemini values in .env (`make doctor` lists what is missing)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
