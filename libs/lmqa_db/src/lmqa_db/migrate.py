"""Create roles and the database, then apply the schema with Alembic and re-apply `db/` policies (KD-12, blueprint 18):

  db/migrations/*.sql   schema; each file is the body of one Alembic revision (lmqa_db/migrations/versions),
                        tracked in alembic_version
  db/policies/*.sql     helper functions, RLS policies, audit functions: idempotent, re-applied every run
  db/roles/grants.sql   least-privilege grants: idempotent, re-applied every run

Databases migrated by the old runner keep their `schema_migrations` table; the first Alembic run stamps the
revision matching the files recorded there, then upgrades from it.

Roles (created here because they need passwords from settings; design "Database roles", KD-2, DEV-13, DEV-48):
  lmqa_owner     owns the schema, runs migrations, never used at runtime
  policy_helper  NOLOGIN; owns the STABLE SECURITY DEFINER lookup helpers (db/policies/95_helper_owner.sql)
  lmqa_app       MVP data plane, NOBYPASSRLS: sees content only through row-level security
  svc_*          one NOBYPASSRLS login role per service (DB_SERVICE_ROLES), owns nothing
  lmqa_system    removed (DEV-13): dropped if it still exists; only if it still holds privileges somewhere is it
                 left NOLOGIN NOBYPASSRLS instead (db/roles/grants.sql then revokes its grants here)
"""

from __future__ import annotations

from pathlib import Path

import psycopg
from alembic import command
from alembic.config import Config
from alembic.runtime.migration import MigrationContext
from alembic.script import ScriptDirectory
from psycopg import sql
from sqlalchemy import Connection, create_engine, inspect, text
from sqlalchemy.pool import NullPool

from lmqa_models.envfile import ROOT
from lmqa_models.settings import DB_SERVICE_ROLES, Settings

DB_DIR = ROOT / "db"
ALEMBIC_INI = Path(__file__).resolve().parents[2] / "alembic.ini"
# Login roles. None of them may bypass RLS (G1.2); the passwords come from settings by name only.
# One NOBYPASSRLS role per service (blueprint 9.2, 16.3): LMQA_DB_<ROLE>_PASSWORD, generated by `make setup`.
SERVICE_ROLES = DB_SERVICE_ROLES
ROLES = ("lmqa_owner", "lmqa_app", *SERVICE_ROLES)
HELPER_OWNER = "policy_helper"
RETIRED_ROLES = ("lmqa_system",)


def _password(settings: Settings, role: str) -> str:
    value = {
        "lmqa_owner": settings.db_owner_password,
        "lmqa_app": settings.db_app_password,
        **dict(settings.db_role_passwords),
    }.get(role)
    if not value:
        raise RuntimeError(f"Password for {role} is not set. Run: make setup")
    return value


def _exists(cur: psycopg.Cursor, role: str) -> bool:
    cur.execute("select 1 from pg_roles where rolname = %s", [role])
    return cur.fetchone() is not None


def _login_works(settings: Settings, role: str) -> bool:
    try:
        with psycopg.connect(settings.dsn(role, database="postgres"), connect_timeout=5):
            return True
    except psycopg.OperationalError:
        return False


def _drop_retired(cur: psycopg.Cursor, role: str) -> None:
    """Drop a removed role. A role that still holds privileges or owns objects in some database cannot be dropped
    from here; it is then made NOLOGIN NOBYPASSRLS, so it can neither connect nor bypass RLS."""
    try:
        with cur.connection.transaction():
            cur.execute(sql.SQL("drop role {}").format(sql.Identifier(role)))
    except psycopg.errors.DependentObjectsStillExist:
        cur.execute(sql.SQL("alter role {} with nologin nobypassrls").format(sql.Identifier(role)))


def bootstrap(settings: Settings, database: str) -> None:
    """Idempotently create roles, the database and the vector extension (superuser, local only)."""
    with psycopg.connect(settings.dsn("postgres"), autocommit=True) as conn, conn.cursor() as cur:
        # Resolve every password first: a missing one fails before anything changes.
        passwords = {role: _password(settings, role) for role in ROLES}
        for role in ROLES:
            exists = _exists(cur, role)
            cur.execute(
                sql.SQL(
                    "{} role {} with login nosuperuser nocreatedb nocreaterole nobypassrls"
                ).format(sql.SQL("alter" if exists else "create"), sql.Identifier(role))
            )
            # Re-setting an unchanged password re-salts the SCRAM verifier and invalidates the PgBouncer
            # userlist, so the password is written only when the configured one does not already work.
            if not (exists and _login_works(settings, role)):
                cur.execute(
                    sql.SQL("alter role {} with password {}").format(
                        sql.Identifier(role), sql.Literal(passwords[role])
                    )
                )
        cur.execute(
            sql.SQL(
                "{} role {} with nologin nosuperuser nocreatedb nocreaterole nobypassrls"
            ).format(
                sql.SQL("alter" if _exists(cur, HELPER_OWNER) else "create"),
                sql.Identifier(HELPER_OWNER),
            )
        )
        # lmqa_owner replaces the helpers on every migrate, so it must be able to act as their owner.
        cur.execute(sql.SQL("grant {} to lmqa_owner").format(sql.Identifier(HELPER_OWNER)))
        for role in RETIRED_ROLES:
            if _exists(cur, role):
                _drop_retired(cur, role)
        cur.execute("select 1 from pg_database where datname = %s", [database])
        if not cur.fetchone():
            cur.execute(
                sql.SQL("create database {} owner lmqa_owner").format(sql.Identifier(database))
            )
    with psycopg.connect(settings.dsn("postgres", database=database), autocommit=True) as conn:
        conn.execute("create extension if not exists vector")
        conn.execute("revoke all on schema public from public")
        conn.execute("grant all on schema public to lmqa_owner")
        # ALTER FUNCTION ... OWNER TO policy_helper needs CREATE on the schema for the new owner.
        conn.execute(
            sql.SQL("grant usage, create on schema public to {}").format(
                sql.Identifier(HELPER_OWNER)
            )
        )


def _run_file(conn: psycopg.Connection, path: Path) -> None:
    conn.execute(path.read_text(encoding="utf-8"))  # type: ignore[arg-type]


def alembic_config() -> Config:
    return Config(str(ALEMBIC_INI))


def legacy_head(revisions: list[str], recorded: set[str]) -> str | None:
    """Last revision of the longest base-first prefix whose SQL files are all in `schema_migrations`."""
    current = None
    for rev in revisions:
        if f"{rev}.sql" not in recorded:
            break
        current = rev
    return current


def _legacy_revision(conn: Connection, script: ScriptDirectory) -> str | None:
    """Revision to stamp on a database migrated by the pre-Alembic runner (no `alembic_version` yet)."""
    tables = set(inspect(conn).get_table_names())
    if "alembic_version" in tables or "schema_migrations" not in tables:
        return None
    recorded = {row[0] for row in conn.execute(text("select name from schema_migrations"))}
    base_first = [rev.revision for rev in reversed(list(script.walk_revisions()))]
    return legacy_head(base_first, recorded)


def _allow_owner_version_writes(conn: Connection) -> None:
    """db/policies/15_force_rls.sql forces RLS on every public table, `alembic_version` included. The owner can read
    the version row (it inherits policy_helper's `helper_read`) but, without this policy, cannot move it, so every
    upgrade after the first would fail with "expected to match one row". Idempotent; runs before each upgrade."""
    conn.execute(
        text(
            "do $$ begin"
            " if to_regclass('public.alembic_version') is not null then"
            " drop policy if exists alembic_owner on alembic_version;"
            " create policy alembic_owner on alembic_version for all to lmqa_owner using (true) with check (true);"
            " end if; end $$"
        )
    )


def upgrade(settings: Settings, database: str, target: str = "head") -> list[str]:
    """`alembic upgrade <target>` as lmqa_owner; returns the revisions applied by this run."""
    cfg = alembic_config()
    script = ScriptDirectory.from_config(cfg)
    url = settings.dsn("lmqa_owner", database=database).replace(
        "postgresql://", "postgresql+psycopg://", 1
    )
    engine = create_engine(url, poolclass=NullPool)
    try:
        with engine.begin() as conn:
            cfg.attributes["connection"] = conn
            legacy = _legacy_revision(conn, script)
            if legacy:
                command.stamp(cfg, legacy)
            _allow_owner_version_writes(conn)
            before = MigrationContext.configure(conn).get_current_revision()
            command.upgrade(cfg, target)
    finally:
        engine.dispose()
    return [r.revision for r in reversed(list(script.iterate_revisions(target, before)))]


def pending(settings: Settings, database: str) -> list[str]:
    """Revisions not yet applied to `database`, base first (all of them for a database without Alembic)."""
    script = ScriptDirectory.from_config(alembic_config())
    url = settings.dsn("lmqa_owner", database=database).replace(
        "postgresql://", "postgresql+psycopg://", 1
    )
    engine = create_engine(url, poolclass=NullPool)
    try:
        with engine.connect() as conn:
            tables = set(inspect(conn).get_table_names())
            current = (
                MigrationContext.configure(conn).get_current_revision()
                if "alembic_version" in tables
                else _legacy_revision(conn, script)
            )
    finally:
        engine.dispose()
    return [r.revision for r in reversed(list(script.iterate_revisions("head", current)))]


def apply_policies(settings: Settings, database: str) -> None:
    with psycopg.connect(settings.dsn("lmqa_owner", database=database)) as conn, conn.transaction():
        for path in sorted((DB_DIR / "policies").glob("*.sql")):
            _run_file(conn, path)
        _run_file(conn, DB_DIR / "roles" / "grants.sql")


def apply(settings: Settings, database: str, target: str = "head") -> list[str]:
    applied = upgrade(settings, database, target)
    apply_policies(settings, database)
    return applied


def drop_database(settings: Settings, database: str) -> None:
    with psycopg.connect(settings.dsn("postgres"), autocommit=True) as conn:
        conn.execute(
            sql.SQL("drop database if exists {} with (force)").format(sql.Identifier(database))
        )


def migrate(settings: Settings, database: str | None = None, target: str = "head") -> list[str]:
    """Bootstrap, `alembic upgrade <target>`, then re-apply policies and grants. A database with plaintext rows
    must pass through `tools/db_migrate.py`, which runs the re-encryption job before 0013_drop_plaintext."""
    db = database or settings.db_name
    bootstrap(settings, db)
    return apply(settings, db, target)
